export const UK_CITIES: UkCity[] = [...RAW_UK_CITIES].sort((a, b) =>
  a.name.localeCompare(b.name, "en-GB"),
);

export const UK_CITY_NAMES = UK_CITIES.map((c) => c.name);

export function findUkCity(name: string | null | undefined): UkCity | null {
  if (!name) return null;
  const n = name.trim().toLowerCase();
  // Match exact name first, then tolerate legacy short forms like "Newcastle".
  return (
    UK_CITIES.find((c) => c.name.toLowerCase() === n) ??
    UK_CITIES.find((c) => c.name.toLowerCase().startsWith(n)) ??
    null
  );
}
